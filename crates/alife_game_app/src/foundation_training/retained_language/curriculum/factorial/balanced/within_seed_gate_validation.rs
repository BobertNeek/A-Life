//! Sixteen record-only decisions from saved public starts; no optimizer calls.
use super::super::token_probe::speech;
use super::bounded_tape_probe::{source_actor, write_compressed};
use super::*;
use std::path::PathBuf;

#[derive(Deserialize)]
struct CommonStart {
    seed: u64,
    fixture: usize,
    scene: Scene,
    host: CpuCanonicalCheckpoint,
}

fn read_compressed<T: serde::de::DeserializeOwned>(path: &Path) -> Result<T> {
    Ok(serde_json::from_reader(zstd::stream::read::Decoder::new(
        fs::File::open(path)?,
    )?)?)
}

// Author a stationary initial fixture through the ordinary editor. The second
// placement has zero displacement, hence zero native editor velocity. No tick,
// acquisition, consumption or reward is generated by these setup operations.
fn stationary(w: &mut HeadlessWorld, id: WorldEntityId, position: Vec3f) -> Result<()> {
    w.editor_move_object(id, position)?;
    let position = w.entity(id).ok_or("missing stationary object")?.position;
    w.editor_move_object(id, position)?;
    Ok(())
}

fn normalize_food_position(value: &mut Value, food: WorldEntityId) -> Result<()> {
    let objects = value
        .pointer_mut("/world/world/objects")
        .and_then(Value::as_array_mut)
        .ok_or("no checkpoint objects")?;
    let object = objects
        .iter_mut()
        .find(|o| o["id"] == serde_json::to_value(food).unwrap_or(Value::Null))
        .ok_or("no matched food")?;
    object["position"] = Value::Null;
    Ok(())
}

#[test]
#[ignore = "explicit record-only public within-seed gate diagnostic; maximum 16 decisions"]
fn record_matched_food_report_opportunities() -> Result<()> {
    let source = PathBuf::from(std::env::var("ALIFE_WITHIN_SEED_SOURCE")?);
    let v26 = PathBuf::from(std::env::var("ALIFE_WITHIN_SEED_V26")?);
    let out = PathBuf::from(std::env::var("ALIFE_WITHIN_SEED_OUT")?);
    let (compiled, asset) = source_actor(&source, "MixedGrounded4")?;
    let original: FoundationTrainerCheckpoint =
        read_compressed(&v26.join("actor-Untouched.json.zst"))?;
    let actor = CpuFoundationTrainer::from_checkpoint(
        compiled.phenotype().clone(),
        asset,
        original.clone(),
    )?;
    assert_eq!(actor.optimizer_step(), 436);
    assert_eq!(actor.checkpoint(), original);
    let cases: Vec<CommonStart> = read_compressed(&v26.join("common-assessment-starts.json.zst"))?;
    assert_eq!(cases.len(), 2);
    assert_eq!(
        cases.iter().map(|c| c.seed).collect::<Vec<_>>(),
        [19_310_729, 19_508_423]
    );
    fs::create_dir(&out)?;
    let started = Instant::now();
    let source_hash = identity(&original)?;
    let mut calls = 0usize;
    let mut records = vec![];
    let mut forks = vec![];
    let mut finals = vec![];
    let mut trace = zstd::stream::write::Encoder::new(
        fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(out.join("native-tapes.jsonl.zst"))?,
        3,
    )?;
    for case in cases {
        let mut parent = CpuCanonicalHost::from_checkpoint(case.host, &actor)?;
        let id = parent.world().organism_entity_ids()[0].0;
        assert_eq!(owners(parent.world(), case.scene), [None, None]);
        // Common toy/distractor geometry is shared, including native private
        // histories already saved in V26. No additional preparation decision.
        unseen_transfer::place_case(parent.world_mut(), case.scene, case.fixture)?;
        for object in [case.scene.food, case.scene.toy] {
            let pos = parent
                .world()
                .entity(object)
                .ok_or("no placed object")?
                .position;
            stationary(parent.world_mut(), object, pos)?;
        }
        let common = serde_json::to_value(parent.checkpoint(&actor)?)?;
        write_compressed(&out.join(format!("common-{}.json.zst", case.seed)), &common)?;
        let mut normalized_common = common.clone();
        normalize_food_position(&mut normalized_common, case.scene.food)?;
        let body = parent
            .world()
            .entity(parent.world().organism_entity_ids()[0].1)
            .ok_or("no body")?
            .clone();
        for (condition, distance) in [("near_opportunity", 0.37f32), ("far_opportunity", 1.60f32)] {
            let mut host = parent.snapshot();
            let angle = body.body_yaw + 0.15;
            stationary(
                host.world_mut(),
                case.scene.food,
                Vec3f::new(
                    body.position.x + distance * angle.cos(),
                    body.position.y,
                    body.position.z + distance * angle.sin(),
                ),
            )?;
            let before = serde_json::to_value(host.checkpoint(&actor)?)?;
            let mut normalized = before.clone();
            normalize_food_position(&mut normalized, case.scene.food)?;
            assert_eq!(
                normalized, normalized_common,
                "fixture changed more than initial food position"
            );
            assert_eq!(owners(host.world(), case.scene), [None, None]);
            let initial_grab_legal = host.world().can_grab_target(id, case.scene.food);
            assert_eq!(initial_grab_legal, condition == "near_opportunity");
            let fork = json!({"seed":case.seed,"condition":condition,"food_distance":distance,"food_angle":0.15,"initial_native_grab_legal":initial_grab_legal,"scene":case.scene,"common_full_sha256":identity(&common)?,"branch_full_sha256":identity(&before)?,"all_except_initial_food_position_identical":true,"normalized_full_sha256":identity(&normalized)?,"initial_prompted_cooldown_ready":host.world().neural_speech_cooldown_ready(id,true),"source_prior_replay_events":common.pointer("/residents/0/replay").and_then(Value::as_array).map(|v|v.iter().map(|r|r["event"].clone()).collect::<Vec<_>>())});
            write_compressed(
                &out.join(format!("start-{}-{condition}.json.zst", case.seed)),
                &before,
            )?;
            forks.push(fork);
            let mut events = Vec::<Event>::new();
            for offset in 0..4 {
                let cue = if offset % 2 == 0 {
                    let pos = speech_position(host.world())?;
                    let before_audio = frozen_causal::before_audio(&host, &actor)?;
                    host.world_mut().emit_player_tokens(
                        Some(id),
                        pos,
                        Lesson::GetFood
                            .words()
                            .into_iter()
                            .map(LanguageTokenId::new)
                            .collect::<std::result::Result<_, _>>()?,
                    )?;
                    Some(
                        json!({"position":pos,"tokens":Lesson::GetFood.words(),"proof":frozen_causal::after_audio(before_audio,&host,&actor)?}),
                    )
                } else {
                    None
                };
                let owned_before = owners(host.world(), case.scene);
                let ready = host.world().neural_speech_cooldown_ready(id, true);
                let unprompted_ready = host.world().neural_speech_cooldown_ready(id, false);
                let pre = host.checkpoint(&actor)?;
                if calls >= 16 {
                    return Err("refusing native decision 17".into());
                }
                calls += 1;
                write_json(
                    &out.join(format!("decision-attempt-{calls:02}.json")),
                    &json!({"reserved_native_step":calls,"hard_maximum":16,"seed":case.seed,"condition":condition,"offset":offset,"pre_full_sha256":identity(&pre)?}),
                )?;
                let result = host.step(&actor, 1.)?;
                assert_eq!(result.decisions.len(), 1);
                let row = &result.decisions[0];
                no_teacher_or_prior(row)?;
                let owned_after = owners(host.world(), case.scene);
                let current = physical_event(row, case.scene, owned_before, owned_after)?;
                let tick = row.patch.pre_action().tick.raw();
                let emitted = host
                    .world()
                    .audible_utterances()
                    .into_iter()
                    .filter(|u| {
                        u.source_kind == UtteranceSourceKind::Creature
                            && u.speaker_id == Some(id)
                            && u.emitted_tick == row.patch.pre_action().tick
                    })
                    .collect::<Vec<_>>();
                let declare = row.patch.selected_bundle().is_some_and(|b| {
                    b.channels.iter().any(|c| {
                        c.channel == MotorChannel::Vocal && c.payload.values.get(1) == Some(&0)
                    })
                });
                let matching = declare
                    && emitted.iter().any(|u| {
                        u.tokens.iter().map(|t| t.raw()).collect::<Vec<_>>()
                            == Lesson::GetFood.words()
                    });
                let support = events
                    .iter()
                    .rev()
                    .find(|e| e.lesson == Lesson::GetFood && e.tick < tick && tick - e.tick <= 3);
                let label = if !matching {
                    "abstain_no_actual_matching_declare"
                } else if support.is_some() {
                    "supported_recent"
                } else if current.is_none()
                    && events.iter().all(|e| e.lesson != Lesson::GetFood)
                    && owned_before[0].is_none()
                    && owned_after[0].is_none()
                {
                    "unsupported_observed_prefix"
                } else {
                    "abstain_concurrent_or_historical"
                };
                let sensory = row.patch.pre_action().perception().sensory();
                let heard = sensory
                    .language_context
                    .heard_tokens
                    .iter()
                    .take(2)
                    .map(|t| t.as_ref().map(|t| t.token_id))
                    .collect::<Vec<_>>();
                let language = sensory.language_prior_neural_lanes();
                let source_start =
                    actor.phenotype().candidate_decoder().motor_start() as usize + 128;
                let raw = speech(
                    &actor,
                    &row.final_features,
                    &row.replay_tick.effective_weight_offsets,
                );
                let organism = host
                    .world()
                    .organism_registry()
                    .get(id)
                    .ok_or("missing body after step")?;
                let bio = organism.biochemistry();
                let record = json!({"seed":case.seed,"condition":condition,"offset":offset,"tick":tick,"requested":"GetFood","cue":cue,"first_two_heard_slots":heard,"first16_native_language_lanes":&language[..16],"prompted_cooldown_ready":ready,"unprompted_cooldown_ready":unprompted_ready,"owned_before":owned_before,"owned_after":owned_after,"prior_actual_events":events,"recent_matching_support":support,"latest_prior_event_matches":events.last().is_some_and(|e|e.lesson==Lesson::GetFood&&tick-e.tick<=3),"current_actual_event":current,"actual_food_consumption":consequences(row,case.scene).0,"actual_emitted":emitted,"actual_matching_declare":matching,"label":label,"source_decoder_inputs_32":&row.final_features[source_start..source_start+32],"raw_speech_outputs_six_steps":raw,"conditional_native_payload":decode_cpu_speech(&actor,&row.final_features,&row.replay_tick.effective_weight_offsets)?,"native_full_row_sha256":identity(row)?,"pre_full_sha256":identity(&pre)?,"post_full_sha256":identity(&host.checkpoint(&actor)?)?,"global_actor_sha256":source_hash,"biological_reward":row.biological_reward,"safety":{"alive":organism.lifecycle().is_alive(),"energy":bio.body.energy,"health":bio.body.health,"injury":bio.body.injury,"pain":bio.homeostasis.drives.pain}});
                write_compressed(
                    &out.join(format!("native-decision-{calls:02}.json.zst")),
                    &json!({"record":record,"full_native_row":row,"full_host_before":pre,"full_host_after":host.checkpoint(&actor)?}),
                )?;
                writeln!(trace, "{}", json!({"record":record,"full_native_row":row}))?;
                records.push(record);
                assert_eq!(
                    actor.checkpoint(),
                    original,
                    "record-only collection changed actor or optimizer"
                );
                if let Some(event) = current {
                    events.push(event);
                }
            }
            let cp = host.checkpoint(&actor)?;
            let file = format!("final-{}-{condition}.json.zst", case.seed);
            write_compressed(&out.join(&file), &cp)?;
            // Restore verification consumes no additional decision.
            let restored = CpuCanonicalHost::from_checkpoint(cp.clone(), &actor)?;
            assert_eq!(identity(&restored.checkpoint(&actor)?)?, identity(&cp)?);
            finals.push(json!({"seed":case.seed,"condition":condition,"checkpoint":file,"checkpoint_sha256":identity(&cp)?,"exact_restore_without_new_steps":true}));
        }
    }
    trace.finish()?;
    assert_eq!(calls, 16);
    assert_eq!(actor.checkpoint(), original);
    write_json(
        &out.join("results.json"),
        &json!({"kind":"experimental-within-seed-record-only-gate-v28","execution_domain":"native-cpu","total_native_steps_and_scored_decisions":calls,"preparation_decisions":0,"gradient_probes":0,"native_or_shadow_optimizer_updates":0,"provider_calls":0,"source_actor_sha256":source_hash,"final_actor_sha256":identity(&actor.checkpoint())?,"source_optimizer_step":actor.optimizer_step(),"all_actor_weights_moments_ages_config_mask_exact":true,"matching_forks":forks,"records":records,"final_private_states":finals,"elapsed_seconds":started.elapsed().as_secs_f64(),"limitations":["Two V26 saved seeds, previously assessed but excluded from the five-tape separator fit; not newly independent seeds.","Food distance changes physical affordances/candidates. Later actions, sensory input, biology/private history and cooldown may diverge naturally; only initial food position differs.","Only actual matching Declare emissions are labeled. Recent physical ownership supports positives; unsupported labels refer to the observed prefix plus saved initially unheld food and prehistory.","Frozen offline coefficients are never installed or used to choose native actions. No training, refitting, reset, promotion or external model call."]}),
    )?;
    Ok(())
}
