use alife_core::*;
use alife_world::*;

fn fixture() -> HeadlessWorld {
    let mut world = HeadlessScenarioBuilder::new(921)
        .agent("a", OrganismId(1), Vec3f::ZERO)
        .build()
        .unwrap();
    let genome = CreatureGenome::early_mammal_founder(
        922,
        FoundationGeneticIdentity::new(10, 1, 7, BrainCapacityClass::N512_ID).unwrap(),
    )
    .unwrap();
    let phenotype = genome.express().unwrap();
    let record = WorldOrganismRecord::newborn(
        OrganismId(1),
        world.entity_id("a").unwrap(),
        genome,
        phenotype,
        Tick::ZERO,
    )
    .unwrap();
    world.register_organism_record(record).unwrap();
    world
}

fn restore(world: &HeadlessWorld) -> HeadlessWorld {
    let save = PortableSaveFile::from_headless_world(
        "pulse",
        world,
        RuntimeConfig::deterministic_default(921, BrainScaleTier::Nano512),
        AssetManifest::empty(),
        vec![],
    )
    .unwrap();
    PortableSaveFile::from_json_str(&serde_json::to_string(&save).unwrap())
        .unwrap()
        .restore_headless_world()
        .unwrap()
}

#[test]
fn prechange_record_bytes_and_body_identity_remain_exact_without_a_pulse() {
    // Generated by the same fixture on pre-change 3ee6b035, not this serializer.
    fn digest(bytes: &[u8]) -> u64 {
        bytes.iter().fold(0xcbf29ce484222325_u64, |digest, byte| {
            (digest ^ u64::from(*byte)).wrapping_mul(0x100000001b3)
        })
    }
    let world = fixture();
    let record = world.organism_registry().get(OrganismId(1)).unwrap();
    let bytes = serde_json::to_vec(record).unwrap();
    assert_eq!(bytes.len(), 42485);
    assert_eq!(digest(&bytes), 0xfad04f8ef36c503f);
    let legacy = include_bytes!("fixtures/prediction_pulse_legacy_biochemistry.json");
    assert_eq!(legacy.len(), 2577);
    assert_eq!(digest(legacy), 0xab1eae2812090d1f);
    let biology: BiochemistryState = serde_json::from_slice(legacy).unwrap();
    biology.validate_against(record.phenotype()).unwrap();
    assert_eq!(serde_json::to_vec(&biology).unwrap(), legacy);
    assert_eq!(
        record.state_graph().body_biochemistry.content_digest,
        [
            17344954632967425618,
            14851066940507429741,
            8584149261425789045,
            6156142855137011306
        ]
    );
    let restored = restore(&world);
    assert_eq!(
        serde_json::to_vec(restored.organism_registry().get(OrganismId(1)).unwrap()).unwrap(),
        bytes
    );
}

#[test]
fn exact_world_state_retains_a_pulse_and_consumes_it_during_idle_or_sleep_biology() {
    let mut world = fixture();
    let mut record = world
        .organism_registry()
        .get(OrganismId(1))
        .unwrap()
        .clone();
    let compiler_identity = record.phenotype().clone();
    record
        .stage_prediction_residual_pulse(ExperienceSequenceId::new(1).unwrap(), 7, 0.9, 1.0)
        .unwrap();
    world.replace_organism_record_exact(record).unwrap();
    let mut restored = restore(&world);
    assert_eq!(
        serde_json::to_vec(world.organism_registry().get(OrganismId(1)).unwrap()).unwrap(),
        serde_json::to_vec(restored.organism_registry().get(OrganismId(1)).unwrap()).unwrap()
    );
    world.try_advance_tick().unwrap();
    restored.try_advance_tick().unwrap();
    assert_eq!(
        world
            .organism_registry()
            .get(OrganismId(1))
            .unwrap()
            .biochemistry(),
        restored
            .organism_registry()
            .get(OrganismId(1))
            .unwrap()
            .biochemistry()
    );
    assert!(serde_json::to_value(
        restored
            .organism_registry()
            .get(OrganismId(1))
            .unwrap()
            .biochemistry()
    )
    .unwrap()
    .get("pending_prediction_residual")
    .is_none());
    let mut after_consumption = restore(&restored);
    restored.try_advance_tick().unwrap();
    after_consumption.try_advance_tick().unwrap();
    assert_eq!(
        restored
            .organism_registry()
            .get(OrganismId(1))
            .unwrap()
            .biochemistry(),
        after_consumption
            .organism_registry()
            .get(OrganismId(1))
            .unwrap()
            .biochemistry()
    );
    assert_eq!(
        after_consumption
            .organism_registry()
            .get(OrganismId(1))
            .unwrap()
            .phenotype(),
        &compiler_identity
    );
}

#[test]
fn a_failed_record_update_preserves_pending_pulse_and_exact_state_reference() {
    let world = fixture();
    let mut record = world
        .organism_registry()
        .get(OrganismId(1))
        .unwrap()
        .clone();
    record
        .stage_prediction_residual_pulse(ExperienceSequenceId::new(1).unwrap(), 7, 0.9, 1.0)
        .unwrap();
    let before = serde_json::to_vec(&record).unwrap();
    let stale = NeuralEmissionFrame::new(Tick(2), 8, vec![]).unwrap();
    assert!(record
        .advance_biology_with_neural_emission(Tick(1), BodyEventDelta::zero(), &stale)
        .is_err());
    assert_eq!(serde_json::to_vec(&record).unwrap(), before);
    record
        .advance_biology(
            Tick(1),
            BodyEventDelta {
                sleep_recovery: 1.0,
                ..BodyEventDelta::zero()
            },
        )
        .unwrap();
    record.validate_contract().unwrap();
    assert!(serde_json::to_value(record.biochemistry())
        .unwrap()
        .get("pending_prediction_residual")
        .is_none());
}
